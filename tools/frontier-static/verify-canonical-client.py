#!/usr/bin/env python3
"""Verify every exported wire-page field with unmodified3640684 readers.

Requires CPython3.12 and an existing owned candidate runtime/client-wire export.
Imports only the client's generated FlatBuffers package, never the game runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

CLIENT_SHA256 = "2f43f4b8d34632b5d5fdc7b58af93364f606bd9ba67fcada588565ee0628122c"


def sha(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1048576), b""):
            value.update(block)
    return value.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--client-archive", type=Path, required=True)
    parser.add_argument("--wire-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 12):
        raise RuntimeError("Exact client generated bytecode requires CPython3.12")
    if sha(args.client_archive) != CLIENT_SHA256:
        raise ValueError("Unrecognized3640684 client archive")
    sys.path.insert(0, str(args.client_archive.resolve()))
    from flatbuffers.generated.eve.universe.v1.UniverseDelta import UniverseDelta
    manifest = json.loads((args.wire_dir / "manifest.json").read_text())
    if manifest["format"] != "evejs-canonical-wire-validation-v1" or manifest["clientBuild"] != 3640684:
        raise ValueError("Unrecognized candidate wire manifest")
    checks, systems, pages = 0, 0, 0

    def compare(expected, actual, path):
        nonlocal checks
        if actual is None:
            raise AssertionError("Missing decoded table " + path)
        for field, value in expected.items():
            name = field[0].upper() + field[1:]
            getter = getattr(actual, name)
            key = path + "." + field
            if isinstance(value, list):
                assert getattr(actual, name + "Length")() == len(value), key
                checks += 1
                for index, row in enumerate(value):
                    if isinstance(row, dict):
                        compare(row, getter(index), key + "." + str(index))
                    else:
                        assert getter(index) == row, key
                        checks += 1
            elif isinstance(value, dict):
                compare(value, getter(), key)
            else:
                decoded = getter()
                if isinstance(decoded, bytes):
                    decoded = decoded.decode("utf-8")
                # JSON.stringify prints a shortest round-tripping decimal for
                # JS Number; Python may parse that spelling as an arbitrary
                # precision int. Reconstruct its Float64 value for float slots.
                if isinstance(decoded, float) and isinstance(value, int):
                    value = float(value)
                if field == "security":
                    value = struct.unpack("<f", struct.pack("<f", value))[0]
                assert decoded == value, (key, decoded, value)
                checks += 1

    for page in manifest["pages"]:
        paths = [args.wire_dir / page[k] for k in ("expected", "payload")]
        for p in paths:
            if p.is_symlink() or p.parent.resolve() != args.wire_dir.resolve():
                raise ValueError("Wire page escapes export directory")
        expected_path, payload_path = paths
        assert sha(expected_path) == page["expectedSHA256"]
        assert sha(payload_path) == page["payloadSHA256"]
        expected = json.loads(expected_path.read_text())
        payload = payload_path.read_bytes()
        compare(expected, UniverseDelta.GetRootAsUniverseDelta(payload, 0), "UniverseDelta")
        assert len(expected["systems"]) == page["systems"]
        systems += page["systems"]
        pages += 1
    assert systems == manifest["systems"]
    report = {"status": "pass", "clientBuild": 3640684, "sourceBuild": 3572727,
              "clientArchiveSHA256": CLIENT_SHA256, "worldRevision": manifest["worldRevision"],
              "contentRevision": manifest["contentRevision"], "baseRevision": manifest["baseRevision"],
              "systems": systems, "pages": pages, "fieldChecks": checks,
              "method": "Existing server encoder output compared field-by-field through exact unmodified3640684 generated readers; float slots reconstruct JavaScriptNumber Float64 values and security uses schemaFloat32. No native game, player login or rendering."}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report))


if __name__ == "__main__":
    main()
