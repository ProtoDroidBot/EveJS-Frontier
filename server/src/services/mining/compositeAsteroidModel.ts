"use strict";

const { createHash } = require("node:crypto");
const { deflateSync, inflateSync } = require("node:zlib");
const templates = require("./compositeTemplates3640684.json");

const MAX_COMPOSITE_CELLS = 32768;
const COMPOSITE_CLIENT_BUILD = 3640684;
const templateGrids = new Map<string, readonly CompositeCell[]>();
const templateExtents = templates.templates.map(template => Math.max(...template.cells.map(
  ([x, y, z]) => Math.hypot(Math.abs(x) + 0.5, Math.abs(y) + 0.5, Math.abs(z) + 0.5),
)));
const COMPOSITE_MATERIALS = Object.freeze([
  "feldspar", "sulfide", "iridosmine", "methane", "ptpd", "kerogen", "tholin", "aromatic",
]);

type Vector3 = { x: number; y: number; z: number };
type CompositeCell = Vector3 & { index: number; material: string; yieldTypeID: number };
type CompositeModel = {
  version: number; clientBuild: number; itemID: number; typeID: number; templateIndex: number;
  yieldTypeID: number; material: string; radius: number; spacing: number;
  recipeHash: string; recipe: Record<string, any>; grid: readonly CompositeCell[];
};

function positiveID(value: unknown, name: string): number {
  if (!Number.isSafeInteger(value) || Number(value) <= 0) throw new RangeError(`${name} must be a positive safe integer`);
  return Number(value);
}

function cellCount(value: unknown): number {
  if (!Number.isSafeInteger(value) || Number(value) < 1 || Number(value) > MAX_COMPOSITE_CELLS) {
    throw new RangeError(`gridLength must be between 1 and ${MAX_COMPOSITE_CELLS}`);
  }
  return Number(value);
}

function checkedVector(value: Vector3, name: string): Vector3 {
  if (!value || ![value.x, value.y, value.z].every(Number.isFinite)) throw new RangeError(`${name} must be a finite vector`);
  return value;
}

function checkedMinedSet(gridLength: number, indices: Iterable<number>): Set<number> {
  cellCount(gridLength);
  const result = new Set<number>();
  for (const index of indices) {
    if (!Number.isSafeInteger(index) || index < 0 || index >= gridLength) throw new RangeError("Mined cell index is outside the original grid");
    result.add(index);
  }
  return result;
}

/**
 * Use an explicit server recipe understood by the unmodified 3640684 client.
 * Coordinates were generated by that client's pure build_grid function, with
 * its Python RNG and compact-list ordering. Changing material, ore identity,
 * spacing or radius_scale does not alter this single-material profile's grid.
 * Do not add arbitrary seeds/shapes here without regenerating exact templates.
 */
function createCompositeModel(options: {
  itemID: number; typeID: number; yieldTypeID: number; material: string;
  radius: number; templateIndex?: number;
}): CompositeModel {
  const itemID = positiveID(options.itemID, "itemID");
  const typeID = positiveID(options.typeID, "typeID");
  const yieldTypeID = positiveID(options.yieldTypeID, "yieldTypeID");
  if (!COMPOSITE_MATERIALS.includes(options.material)) throw new RangeError("Unsupported composite material");
  if (!Number.isFinite(options.radius) || options.radius <= 0 || options.radius > 1_000_000) {
    throw new RangeError("Composite radius must be positive and at most 1,000,000 metres");
  }
  const templateIndex = options.templateIndex ?? itemID % templates.templates.length;
  if (!Number.isInteger(templateIndex) || templateIndex < 0 || templateIndex >= templates.templates.length) {
    throw new RangeError("Unsupported composite template index");
  }
  const template = templates.templates[templateIndex];
  cellCount(template.cells.length);
  // The circumsphere includes every voxel cube, preserving the scene's radius.
  const extent = templateExtents[templateIndex];
  const spacing = options.radius / extent;
  const recipe = {
    ...templates.recipe,
    seed: template.seed,
    spacing,
    radius_scale: spacing / 35,
    layers: [{ depthLo: 0, depthHi: 1, materials: [{
      material: options.material, typeID: yieldTypeID, weight: 1,
      morphology: "massive", self_affinity: 0,
    }] }],
  };
  const recipeHash = createHash("sha256").update(JSON.stringify({
    version: 1, clientBuild: COMPOSITE_CLIENT_BUILD, archiveSHA256: templates.archiveSHA256,
    typeID, recipe,
  })).digest("hex");
  const gridKey = `${templateIndex}:${options.material}:${yieldTypeID}`;
  let grid = templateGrids.get(gridKey);
  if (!grid) {
    grid = Object.freeze(template.cells.map(([x, y, z], index) => Object.freeze({
      index, x, y, z, material: options.material, yieldTypeID,
    })));
    // Retain common templates while bounding callers supplying unusual ore IDs.
    if (templateGrids.size >= 512) templateGrids.delete(templateGrids.keys().next().value);
    templateGrids.set(gridKey, grid);
  }
  Object.freeze(recipe.layers[0].materials[0]);
  Object.freeze(recipe.layers[0].materials);
  Object.freeze(recipe.layers[0]);
  Object.freeze(recipe.layers);
  Object.freeze(recipe);
  return Object.freeze({ version: 1, clientBuild: COMPOSITE_CLIENT_BUILD, itemID, templateIndex,
    typeID, yieldTypeID, material: options.material, radius: options.radius,
    spacing, recipeHash, recipe, grid: Object.freeze(grid) });
}

/** Client mined_blob/apply_mined_blob (1803/1820): LSB-first original grid indices. */
function encodeMinedSet(gridLength: number, indices: Iterable<number>): Buffer | null {
  const mined = checkedMinedSet(gridLength, indices);
  if (!mined.size) return null;
  const bits = Buffer.alloc(Math.ceil(gridLength / 8));
  for (const index of mined) bits[index >> 3] |= 1 << (index & 7);
  return deflateSync(bits, { level: 6 });
}

function decodeMinedSet(gridLength: number, blob: Buffer | null): number[] {
  cellCount(gridLength);
  if (blob === null) return [];
  if (!Buffer.isBuffer(blob) || blob.length > MAX_COMPOSITE_CELLS) throw new RangeError("Invalid composite mined-set blob");
  const length = Math.ceil(gridLength / 8);
  const bits = inflateSync(blob, { maxOutputLength: length });
  if (bits.length !== length) throw new RangeError("Composite mined-set length differs from its original grid");
  const padding = gridLength & 7;
  if (padding && bits[length - 1] >> padding) throw new RangeError("Composite mined-set has out-of-range padding bits");
  const result = [];
  for (let index = 0; index < gridLength; index += 1) {
    if (bits[index >> 3] & (1 << (index & 7))) result.push(index);
  }
  return result;
}

function compositeCellPosition(model: CompositeModel, index: number): Vector3 {
  if (!Number.isInteger(index) || !model.grid[index]) throw new RangeError("Unknown composite cell index");
  const cell = model.grid[index];
  return { x: cell.x * model.spacing, y: cell.y * model.spacing, z: cell.z * model.spacing };
}

/** Find the closest remaining voxel's cube surface, measured in local metres. */
function selectNearestCompositeVoxel(model: CompositeModel, indices: Iterable<number>, origin: Vector3) {
  checkedVector(origin, "origin");
  const mined = checkedMinedSet(model.grid.length, indices);
  let best = null;
  const half = model.spacing / 2;
  for (const cell of model.grid) {
    if (mined.has(cell.index)) continue;
    const position = compositeCellPosition(model, cell.index);
    const distance = Math.hypot(...["x", "y", "z"].map(axis => Math.max(0, Math.abs(origin[axis] - position[axis]) - half)));
    if (best === null || distance < best.distance) best = { ...cell, position, distance };
  }
  return best;
}

/** Exact ray/cube intersection over bounded authoritative surviving geometry. */
function raycastCompositeVoxel(model: CompositeModel, indices: Iterable<number>, origin: Vector3, direction: Vector3) {
  checkedVector(origin, "origin");
  checkedVector(direction, "direction");
  const length = Math.hypot(direction.x, direction.y, direction.z);
  if (!(length > 0) || !Number.isFinite(length)) throw new RangeError("direction must be nonzero");
  const mined = checkedMinedSet(model.grid.length, indices);
  const half = model.spacing / 2;
  let best = null;
  for (const cell of model.grid) {
    if (mined.has(cell.index)) continue;
    const position = compositeCellPosition(model, cell.index);
    let near = 0;
    let far = Infinity;
    for (const axis of ["x", "y", "z"]) {
      const d = direction[axis] / length;
      const lo = position[axis] - half;
      const hi = position[axis] + half;
      if (d === 0) {
        if (origin[axis] < lo || origin[axis] > hi) { far = -1; break; }
      } else {
        const a = (lo - origin[axis]) / d;
        const b = (hi - origin[axis]) / d;
        near = Math.max(near, Math.min(a, b));
        far = Math.min(far, Math.max(a, b));
      }
    }
    if (far >= near && (best === null || near < best.distance)) best = { ...cell, position, distance: near };
  }
  return best;
}

module.exports = {
  COMPOSITE_CLIENT_BUILD, COMPOSITE_MATERIALS, MAX_COMPOSITE_CELLS,
  createCompositeModel, encodeMinedSet, decodeMinedSet, compositeCellPosition,
  selectNearestCompositeVoxel, raycastCompositeVoxel,
};
